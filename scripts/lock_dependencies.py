"""Lock the validated Linux/Python 3.12 environment using official PyPI hashes.

Install the pinned input requirements first and run pip check. This reads installed
distribution metadata (never imports dependency code), verifies every version
constraint in its dependency closure, then records release artifact hashes from
PyPI. Installation uses wheels only and --require-hashes; a mismatch fails closed.
"""
from __future__ import annotations
import asyncio
import importlib.metadata as metadata
import re
from pathlib import Path
import httpx
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
from packaging.version import Version

ROOT = Path(__file__).resolve().parents[1]


def inputs(path: Path) -> list[Requirement]:
    if not path.resolve().is_relative_to(ROOT):
        raise ValueError("requirements includes must remain inside the project")
    requirements = []
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line.startswith("-r "):
            requirements.extend(inputs(path.parent / line[3:].strip()))
        elif line:
            requirements.append(Requirement(line))
    return requirements


def closure(roots: list[Requirement]) -> dict[str, str]:
    pending = list(roots)
    extras: dict[str, set[str]] = {}
    packages = {}
    while pending:
        requirement = pending.pop()
        if requirement.marker and not requirement.marker.evaluate({"extra": ""}):
            continue
        distribution = metadata.distribution(requirement.name)
        if distribution.version not in requirement.specifier:
            raise ValueError(f"installed {requirement.name}=={distribution.version} violates {requirement}")
        name = canonicalize_name(distribution.metadata["Name"])
        selected = {"", *requirement.extras}
        if name in extras and selected <= extras[name]:
            continue
        extras.setdefault(name, set()).update(selected)
        packages[name] = distribution.version
        for raw in distribution.requires or []:
            dep = Requirement(raw)
            if not dep.marker or any(dep.marker.evaluate({"extra": extra}) for extra in extras[name]):
                # The parent extra has already been evaluated; don't reevaluate
                # it under the child's empty extra on the next iteration.
                dep.marker = None
                pending.append(dep)
    return packages


async def main() -> None:
    targets = {
        "api/requirements.lock": closure(inputs(ROOT / "api/requirements.txt")),
        "indexer/requirements.lock": closure(inputs(ROOT / "indexer/requirements.txt")),
        "requirements-dev.lock": closure(inputs(ROOT / "api/requirements-dev.txt") + inputs(ROOT / "indexer/requirements-dev.txt")),
        "requirements-audit.lock": closure(inputs(ROOT / "api/requirements-dev.txt") + inputs(ROOT / "indexer/requirements-dev.txt") + [Requirement("playwright==1.56.0")]),
    }
    wanted = {name: version for packages in targets.values() for name, version in packages.items()}
    semaphore = asyncio.Semaphore(6)
    async with httpx.AsyncClient(timeout=60) as client:
        async def fetch(name: str, version: str):
            async with semaphore:
                response = await client.get(f"https://pypi.org/pypi/{name}/{version}/json")
                response.raise_for_status()
                data = response.json()
                if Version(data["info"]["version"]) != Version(version):
                    raise ValueError(f"PyPI version mismatch for {name}")
                hashes = sorted({item["digests"]["sha256"] for item in data["urls"] if item["packagetype"] == "bdist_wheel"})
                if not hashes or any(not re.fullmatch(r"[a-f0-9]{64}", digest) for digest in hashes):
                    raise ValueError(f"no verified wheel hashes for {name}=={version}")
                return name, hashes
        hashes = dict(await asyncio.gather(*(fetch(name, version) for name, version in wanted.items())))
    for path, packages in targets.items():
        lines = ["# Linux/Python 3.12 dependency closure; generated by scripts/lock_dependencies.py.", "# Official PyPI wheel SHA-256 values. Install with --require-hashes --only-binary=:all:."]
        for name, version in sorted(packages.items()):
            lines.append(f"{name}=={version} \\")
            lines.extend("    --hash=sha256:" + digest + (" \\" if i < len(hashes[name]) - 1 else "") for i, digest in enumerate(hashes[name]))
        (ROOT / path).write_text("\n".join(lines) + "\n")
        print(f"{path}: {len(packages)} fully resolved packages", flush=True)


if __name__ == "__main__":
    asyncio.run(main())
